#!/usr/bin/env python3
"""Evaluate the acceptance policy against the labeled dataset with LIVE
Gemini embeddings, and write the numbers the README is allowed to quote.

    doppler run -p genblaze-hackathon -c prd -- .venv/bin/python tools/run_eval.py

Writes eval/report.json (machine truth) and eval/report.md (human view).
The README scorecard must be regenerated from report.json, never hand-typed:
a regenerate-and-diff check keeps the two from drifting.

Honesty contract: every number is reported, including the ones that hurt.
A false auto-reuse (an attribute_swap or same_domain pair the policy served
automatically) is the defect class the operator accepted when choosing the
bolder 0.97 line; this report is where that acceptance gets its price tag.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, "src")

from reprise.embed import GeminiEmbedder, prompt_fingerprint
from reprise.nearmatch import (
    AUTO_REUSE_THRESHOLD,
    REVIEW_THRESHOLD,
    cosine,
)

ROOT = Path(__file__).resolve().parent.parent
DATASET = ROOT / "eval" / "dataset.jsonl"
REPORT_JSON = ROOT / "eval" / "report.json"
REPORT_MD = ROOT / "eval" / "report.md"


def verdict_for(sim: float, exact: bool) -> str:
    if exact or sim >= AUTO_REUSE_THRESHOLD:
        return "reuse"
    if sim >= REVIEW_THRESHOLD:
        return "review"
    return "generate"


def main() -> None:
    rows = [json.loads(line) for line in DATASET.read_text().splitlines() if line.strip()]
    embedder = GeminiEmbedder()

    # One embed per distinct normalized prompt -- mirrors the sidecar cache.
    cache: dict[str, tuple[float, ...]] = {}

    def embed(text: str) -> tuple[float, ...]:
        fp = prompt_fingerprint(text)
        if fp not in cache:
            cache[fp] = embedder.embed(text)
        return cache[fp]

    results = []
    for row in rows:
        exact = prompt_fingerprint(row["library"]) == prompt_fingerprint(row["request"])
        sim = 1.0 if exact else cosine(embed(row["library"]), embed(row["request"]))
        got = verdict_for(sim, exact)
        results.append({**row, "similarity": round(sim, 4), "exact": exact, "got": got})

    by_cat: dict[str, list[dict]] = defaultdict(list)
    for r in results:
        by_cat[r["category"]].append(r)

    # The two headline error classes, named from the user's point of view.
    false_auto = [
        r for r in results
        if r["should"] == "generate" and r["got"] == "reuse"
    ]
    missed_reuse = [
        r for r in results
        if r["should"] == "reuse" and r["got"] == "generate"
    ]
    # Reviews are neither error: they are the band doing its job.
    dangerous_pool = [r for r in results if r["category"] in ("attribute_swap", "same_domain")]

    summary = {
        "thresholds": {"auto_reuse": AUTO_REUSE_THRESHOLD, "review": REVIEW_THRESHOLD},
        "embedder": "gemini-embedding-001 (normalized prompts)",
        "pairs": len(results),
        "distinct_embeddings": len(cache),
        "false_auto_reuse": {
            "count": len(false_auto),
            "of_dangerous_pairs": len(dangerous_pool),
            "rate": round(len(false_auto) / len(dangerous_pool), 4) if dangerous_pool else 0.0,
            "cases": [
                {"library": r["library"], "request": r["request"], "similarity": r["similarity"]}
                for r in false_auto
            ],
        },
        "missed_reuse": {
            "count": len(missed_reuse),
            "of_equivalent_pairs": len([r for r in results if r["should"] == "reuse"]),
            "cases": [
                {"library": r["library"], "request": r["request"], "similarity": r["similarity"]}
                for r in missed_reuse
            ],
        },
        "by_category": {
            cat: {
                "n": len(rs),
                "reuse": sum(1 for r in rs if r["got"] == "reuse"),
                "review": sum(1 for r in rs if r["got"] == "review"),
                "generate": sum(1 for r in rs if r["got"] == "generate"),
                "sim_min": min(r["similarity"] for r in rs),
                "sim_max": max(r["similarity"] for r in rs),
            }
            for cat, rs in sorted(by_cat.items())
        },
    }

    REPORT_JSON.write_text(json.dumps({"summary": summary, "results": results}, indent=2) + "\n")

    lines = [
        "# Policy evaluation (generated by tools/run_eval.py - do not hand-edit)",
        "",
        f"Embedder: {summary['embedder']}. Thresholds: auto-reuse >= "
        f"{AUTO_REUSE_THRESHOLD}, review band [{REVIEW_THRESHOLD}, {AUTO_REUSE_THRESHOLD}).",
        f"{summary['pairs']} labeled pairs, {summary['distinct_embeddings']} distinct embeddings.",
        "",
        "| category | n | reuse | review | generate | sim range |",
        "|---|---|---|---|---|---|",
    ]
    for cat, s in summary["by_category"].items():
        lines.append(
            f"| {cat} | {s['n']} | {s['reuse']} | {s['review']} | {s['generate']} "
            f"| {s['sim_min']:.3f} - {s['sim_max']:.3f} |"
        )
    fa = summary["false_auto_reuse"]
    mr = summary["missed_reuse"]
    lines += [
        "",
        f"**False auto-reuse: {fa['count']} / {fa['of_dangerous_pairs']} dangerous pairs "
        f"({fa['rate']:.1%}).** A false auto-reuse serves a wrong asset with no human in "
        "the loop; this is the accepted cost of the bolder 0.97 line.",
    ]
    for c in fa["cases"]:
        lines.append(f"  - sim {c['similarity']}: '{c['library']}' served for '{c['request']}'")
    lines += [
        "",
        f"**Missed reuse: {mr['count']} / {mr['of_equivalent_pairs']} equivalent pairs.** "
        "A miss regenerates something owned: costs money, harms nobody.",
    ]
    for c in mr["cases"]:
        lines.append(f"  - sim {c['similarity']}: '{c['request']}' regenerated despite '{c['library']}'")
    lines.append("")
    REPORT_MD.write_text("\n".join(lines))

    print(REPORT_MD.read_text())


if __name__ == "__main__":
    main()
